"""Quantum Foundry — Qiskit verification backend.

The schematic frontend compiles the player's graph into an operation list
(gate + qubit indices, q0 = least significant bit, Qiskit convention) and
posts it here. This service rebuilds a real qiskit.QuantumCircuit, checks the
mission contract with Statevector (fidelity, global phase ignored) and
Operator.equiv (unitary equivalence up to one global phase), and samples
measurement counts. It is the authoritative grader; the browser simulator is
a local preview validated against fixtures generated by make_reference.py.
"""
from __future__ import annotations

from typing import Any, Literal, Optional

from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel
from qiskit import QuantumCircuit, qasm2
from qiskit.quantum_info import Operator, Statevector

app = FastAPI(title="Quantum Foundry runner")
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_methods=["*"],
    allow_headers=["*"],
)


class OpModel(BaseModel):
    gate: Literal["X", "Z", "H", "CX"]
    qubits: list[int]


class ExpectModel(BaseModel):
    type: Literal["state", "bits"]
    bits: Optional[str] = None
    amps: Optional[list[list[float]]] = None
    descr: str = ""


class CaseModel(BaseModel):
    id: str
    label: str = ""
    inputs: list[int]
    prep: list[OpModel] = []
    ops: Optional[list[OpModel]] = None
    expect: ExpectModel


class OperatorCheckModel(BaseModel):
    refOps: list[OpModel]
    arity: int
    descr: str = ""


class VerifyRequest(BaseModel):
    numQubits: int
    cases: list[CaseModel]
    operatorCheck: Optional[OperatorCheckModel] = None
    shots: int = 512


def circuit_from_ops(n: int, ops: list[OpModel]) -> QuantumCircuit:
    qc = QuantumCircuit(n)
    for op in ops:
        if op.gate == "X":
            qc.x(op.qubits[0])
        elif op.gate == "Z":
            qc.z(op.qubits[0])
        elif op.gate == "H":
            qc.h(op.qubits[0])
        elif op.gate == "CX":
            qc.cx(op.qubits[0], op.qubits[1])
    return qc


def input_state(n: int, inputs: list[int]) -> Statevector:
    label = "".join(str(inputs[q] if q < len(inputs) else 0) for q in reversed(range(n)))
    return Statevector.from_label(label)


def verify(req: VerifyRequest) -> dict[str, Any]:
    results = []
    all_pass = True
    first_counts: Optional[dict[str, int]] = None

    for case in req.cases:
        if case.ops is None:
            results.append({"id": case.id, "pass": False, "detail": "circuit incomplete"})
            all_pass = False
            continue
        sv = input_state(req.numQubits, case.inputs)
        if case.prep:
            sv = sv.evolve(circuit_from_ops(req.numQubits, case.prep))
        final = sv.evolve(circuit_from_ops(req.numQubits, case.ops))

        if case.expect.type == "bits":
            probs = final.probabilities_dict()
            best, best_p = max(probs.items(), key=lambda kv: kv[1])
            ok = best_p > 1 - 1e-9 and best == case.expect.bits
            detail = f"reads {best} (p={best_p:.3f}), expected {case.expect.bits}"
        else:
            target = Statevector([complex(a[0], a[1]) for a in case.expect.amps or []])
            fid = abs(complex(target.inner(final))) ** 2
            ok = fid > 1 - 1e-9
            detail = f"state fidelity {fid:.6f}"
        if first_counts is None:
            first_counts = {k: int(v) for k, v in final.sample_counts(req.shots).items()}
        results.append({"id": case.id, "pass": bool(ok), "detail": detail})
        all_pass = all_pass and ok

    operator_pass = None
    if req.operatorCheck is not None:
        ops = next((c.ops for c in req.cases if c.ops is not None), None)
        if ops is None:
            operator_pass = False
        else:
            realized = Operator(circuit_from_ops(req.operatorCheck.arity, ops))
            reference = Operator(circuit_from_ops(req.operatorCheck.arity, req.operatorCheck.refOps))
            operator_pass = bool(realized.equiv(reference))  # equal up to one global phase
        all_pass = all_pass and bool(operator_pass)

    failing = [r for r in results if not r["pass"]]
    if all_pass:
        summary = f"all {len(results)} cases pass" + (", full operation equivalent" if operator_pass else "")
    elif failing:
        summary = f"{len(failing)}/{len(results)} cases fail — first: {failing[0]['detail']}"
    else:
        summary = "cases pass, but the full operation is not equivalent to the reference"
    return {
        "allPass": bool(all_pass),
        "summary": summary,
        "results": results,
        "operatorPass": operator_pass,
        "counts": first_counts,
        "source": "qiskit-statevector",
    }


@app.post("/api/verify")
def verify_endpoint(req: VerifyRequest) -> dict[str, Any]:
    return verify(req)


class CodeRequest(BaseModel):
    numQubits: int
    ops: list[OpModel]


@app.post("/api/qasm")
def qasm_endpoint(req: CodeRequest) -> dict[str, str]:
    """Export the compiled circuit as OpenQASM 2.0 (bit order: q0 = LSB)."""
    qc = circuit_from_ops(req.numQubits, req.ops)
    qc.measure_all()
    return {"qasm": qasm2.dumps(qc), "bitOrder": "q0 is least significant (Qiskit)"}


@app.get("/api/health")
def health() -> dict[str, str]:
    import qiskit

    return {"status": "ok", "qiskit": qiskit.__version__}
